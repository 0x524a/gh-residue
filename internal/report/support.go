package report

import (
	"fmt"
	"io"
	"sort"
	"strconv"
	"strings"

	"github.com/0x524a/gh-residue/internal/model"
)

// SupportOpts carries values the Run itself does not hold.
type SupportOpts struct {
	// FirstChanged is what filter-repo printed ("First Changed Commit(s)"), or
	// the value inferred from commit-map order. Empty means unknown.
	FirstChanged []string
	Inferred     bool   // FirstChanged was inferred, not pasted from filter-repo
	LFSFile      string // name of the LFS-orphans file, if filter-repo reported one
}

// Readiness answers "Ready for Support?". GitHub says Support acts only once no
// non-PR refs and no forks hold references to the data. Ref-holding forks are not
// probed yet, so "yes" is unreachable until that surface reports complete.
func Readiness(r *model.Run) (answer, why string) {
	forkRefDone := false
	for _, s := range r.Coverage.Surfaces {
		if s.Surface == model.SurfaceForkRef && s.Complete {
			forkRefDone = true
		}
	}
	for _, f := range r.Findings {
		if f.Status == model.Confirmed {
			switch f.Surface {
			case model.SurfaceBranch, model.SurfaceTag, model.SurfaceForkRef:
				return "no", fmt.Sprintf("%s still holds a reference (%s)", f.Surface, f.Location)
			}
		}
	}
	if !forkRefDone {
		return "unknown", "ref-holding forks were not checked"
	}
	if r.Incomplete() {
		return "unknown", "some checks were incomplete"
	}
	return "yes", "no non-PR references and no forks hold references"
}

// affectedPRs lists distinct PR numbers seen holding an old SHA.
func affectedPRs(r *model.Run) []int {
	seen := map[int]bool{}
	for _, f := range r.Findings {
		if f.Surface != model.SurfacePRRef || f.Status != model.Confirmed {
			continue
		}
		parts := strings.Split(f.Location, "/") // refs/pull/N/head|merge
		if len(parts) >= 3 {
			if n, err := strconv.Atoi(parts[2]); err == nil {
				seen[n] = true
			}
		}
	}
	out := make([]int, 0, len(seen))
	for n := range seen {
		out = append(out, n)
	}
	sort.Ints(out)
	return out
}

// SupportDraft writes a Markdown request for GitHub Support. It is never sent.
// Fork owner usernames are deliberately omitted. The rotation rationale is left
// blank: the tool must not make that claim on the user's behalf.
func SupportDraft(w io.Writer, r *model.Run, o SupportOpts) {
	prs := affectedPRs(r)
	ready, why := Readiness(r)

	fmt.Fprintf(w, "# Request to remove cached views and PR references\n\n")
	fmt.Fprintf(w, "_Draft generated by gh-residue %s. Review every line before sending; nothing was submitted._\n\n", r.ToolVersion)
	fmt.Fprintf(w, "## Repository\n\n`%s`\n\n", r.Repo)

	fmt.Fprintf(w, "## Affected pull requests\n\n")
	if len(prs) == 0 {
		fmt.Fprintf(w, "0 found by gh-residue. If `changed-refs` lists refs/pull entries, use that count instead.\n\n")
	} else {
		fmt.Fprintf(w, "%d (observed holding an old commit: %s). Cross-check with the `refs/pull` count in filter-repo's `changed-refs`.\n\n", len(prs), joinInts(prs))
	}

	fmt.Fprintf(w, "## First Changed Commit(s)\n\n")
	switch {
	case len(o.FirstChanged) == 0:
		fmt.Fprintf(w, "_Not provided. Paste the `NOTE: First Changed Commit(s)` line from git-filter-repo's output._\n\n")
	default:
		for _, s := range o.FirstChanged {
			fmt.Fprintf(w, "- `%s`\n", s)
		}
		if o.Inferred {
			fmt.Fprintf(w, "\n_Inferred from the first changed entry of `commit-map`, not taken from filter-repo's output. Verify against its `NOTE: First Changed Commit(s)` line._\n")
		}
		fmt.Fprintln(w)
	}

	if o.LFSFile != "" {
		fmt.Fprintf(w, "## LFS objects\n\ngit-filter-repo reported orphaned LFS objects; attach `%s`.\n\n", o.LFSFile)
	}

	fmt.Fprintf(w, "## Old commit SHAs\n\n")
	seen := map[string]bool{}
	var shas []string
	for _, f := range r.Findings {
		if !seen[f.OldSHA] {
			seen[f.OldSHA] = true
			shas = append(shas, f.OldSHA)
		}
	}
	for _, s := range shas {
		fmt.Fprintf(w, "- `%s`\n", s)
	}

	fmt.Fprintf(w, "\n## Current exposure (gh-residue, %s)\n\n", r.StartedAt)
	counts := map[model.Surface]int{}
	for _, f := range r.Findings {
		if f.Status == model.Confirmed {
			counts[f.Surface]++
		}
	}
	surfaces := make([]string, 0, len(counts))
	for s := range counts {
		surfaces = append(surfaces, string(s))
	}
	sort.Strings(surfaces)
	if len(surfaces) == 0 {
		fmt.Fprintln(w, "No confirmed exposure in the checked surfaces.")
	}
	for _, s := range surfaces {
		fmt.Fprintf(w, "- %s: %d\n", s, counts[model.Surface(s)])
	}
	if r.Coverage.ForksTotal > 0 {
		fmt.Fprintf(w, "- Forks checked: %d of %d (object resolvable only)\n", r.Coverage.ForksChecked, r.Coverage.ForksTotal)
	}
	fmt.Fprintf(w, "\n**Ready for Support?** %s: %s.\n", ready, why)

	fmt.Fprintf(w, "\n## Why rotating credentials cannot mitigate the risk\n\n")
	fmt.Fprintf(w, "<!-- REQUIRED, write this yourself. GitHub assists only where the risk cannot be mitigated by rotating credentials. gh-residue does not make this claim for you. -->\n\n")
	fmt.Fprintf(w, "_TODO_\n")
}

func joinInts(ns []int) string {
	const max = 20
	var p []string
	for i, n := range ns {
		if i == max {
			p = append(p, fmt.Sprintf("and %d more", len(ns)-max))
			break
		}
		p = append(p, "#"+strconv.Itoa(n))
	}
	return strings.Join(p, ", ")
}
